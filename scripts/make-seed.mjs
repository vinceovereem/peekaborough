// Builds supabase/seed.sql from data/places.json + data/fixtures.json: real places and real events only.
// (Sample reviews/listings/wishes are demo-mode only; a live database should start with real ones.)
import { readFileSync, writeFileSync } from 'node:fs'
const read = f => JSON.parse(readFileSync(new URL(`../data/${f}`, import.meta.url), 'utf8'))
const q = v => v == null ? 'null' : typeof v === 'boolean' || typeof v === 'number' ? String(v) : typeof v === 'object' ? `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb` : `'${String(v).replace(/'/g, "''")}'`

const PLACE_COLS = ['id', 'osm_id', 'slug', 'name', 'category', 'subcategory', 'description', 'address', 'lat', 'lng', 'phone', 'website', 'booking_url', 'hours', 'hours_note', 'extra', 'is_landmark']
const places = read('places.json')
let sql = `-- Generated by scripts/make-seed.mjs — do not edit by hand.\n-- Place data © OpenStreetMap contributors (ODbL). Fixtures: openfootball (public domain).\n\n`
for (let i = 0; i < places.length; i += 200) {
  sql += `insert into public.places (${PLACE_COLS.join(', ')}) values\n`
    + places.slice(i, i + 200).map(p => `(${PLACE_COLS.map(c => q(c === 'subcategory' ? p[c]?.slice(0, 60) : p[c])).join(', ')})`).join(',\n')
    + `\non conflict (osm_id) do nothing;\n\n`
}

// Europe/London wall time -> timestamptz is done by Postgres, so BST/GMT is always right.
const at = (date, time) => `('${date} ${time}'::timestamp at time zone 'Europe/London')`
const events = read('fixtures.json').map(f => `('Arsenal v ${f.opponent.replace(/'/g, "''")}', 'Premier League, ${f.round}. Kick-off times can move for TV.', 'football', 'Emirates Stadium', 51.555045, -0.1084, ${at(f.date, f.time)}, 'https://www.arsenal.com/fixtures', null, 'published')`)
const sat = new Date(); sat.setUTCDate(sat.getUTCDate() + ((6 - sat.getUTCDay() + 7) % 7 || 7))
for (let w = 0; w < 12; w++, sat.setUTCDate(sat.getUTCDate() + 7)) {
  const d = sat.toISOString().slice(0, 10)
  events.push(`('Highbury Fields parkrun', 'Free, timed 5k every Saturday morning.', 'sport', 'Highbury Fields', 51.5497, -0.1015, ${at(d, '09:00')}, 'https://www.parkrun.org.uk/highburyfields/', 0, 'published')`)
  events.push(`('Finsbury Park parkrun', 'Free, timed 5k every Saturday morning.', 'sport', 'Finsbury Park', 51.5703, -0.101, ${at(d, '09:00')}, 'https://www.parkrun.org.uk/finsbury/', 0, 'published')`)
}
sql += `insert into public.events (title, description, kind, venue_name, lat, lng, starts_at, url, price_pence, status) values\n${events.join(',\n')};\n`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`seed.sql: ${places.length} places, ${events.length} events, ${(sql.length / 1024).toFixed(0)} KB`)
